package main

import (
	"testing"
)

func TestSourceCategory(t *testing.T) {
	for _, tt := range []struct{ path, text, want string }{
		{"pkg/implementation.go", "package pkg", productionCategory},
		{"pkg/config.json", "", productionCategory},
		{"guide/README.md", "", docsCategory},
		{"pkg/readme.go", "", productionCategory},
		{"pkg/tests/check.py", "", testsCategory},
		{"pkg/Widget.test.TS", "", testsCategory},
		{"pkg/tests/fixtures/model.go", "// Code generated example. DO NOT EDIT.", fixturesCategory},
		{"pkg/testdata/example.json", "", fixturesCategory},
		{"pkg/tests/mocks/helper.go", "", generatedCategory},
		{"pkg/mock_client.go", "", generatedCategory},
		{"pkg/client.go", "// Code generated example. DO NOT EDIT.\r\npackage pkg", generatedCategory},
		{"pkg/client.ts", "/* @generated by example */", generatedCategory},
		{"pkg/client.ts", "const value = '// @generated';", productionCategory},
		{"pkg/client.ts", "// @generatedata opt-in", productionCategory},
		{"pkg/contests/helper.go", "", productionCategory},
	} {
		if got := sourceCategory(tt.path, []byte(tt.text)); got != tt.want {
			t.Errorf("%s = %s, want %s", tt.path, got, tt.want)
		}
	}
}

func TestParseCategories(t *testing.T) {
	got, err := parseCategories("production, docs,production")
	if err != nil || !got[productionCategory] || !got[docsCategory] || len(got) != 2 {
		t.Fatalf("categories = %v, err = %v", got, err)
	}
	for _, value := range []string{"", "production,", "unknown"} {
		if _, err := parseCategories(value); err == nil {
			t.Errorf("accepted %q", value)
		}
	}
}
